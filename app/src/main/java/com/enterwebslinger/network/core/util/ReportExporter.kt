package com.enterwebslinger.network.core.util

import android.content.Context
import android.content.Intent
import com.enterwebslinger.network.domain.model.DiscoveredDevice
import com.enterwebslinger.network.domain.model.NetworkTopology
import com.enterwebslinger.network.domain.model.PingSummary
import org.json.JSONArray
import org.json.JSONObject
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

object ReportExporter {

    private val dateFormat = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.US)

    fun shareLanScanReport(
        context: Context,
        devices: List<DiscoveredDevice>,
        topology: NetworkTopology,
        formatAsJson: Boolean = false
    ) {
        val now = dateFormat.format(Date())
        val content = if (formatAsJson) {
            val root = JSONObject()
            root.put("title", "Enterweb Slinger - LAN Discovery Report")
            root.put("generatedAt", now)
            root.put("networkSsid", topology.ssid)
            root.put("defaultGateway", topology.defaultGateway)
            root.put("subnet", "${topology.localIpv4}/${topology.subnetCidr}")
            root.put("deviceCount", devices.size)

            val arr = JSONArray()
            devices.forEach { dev ->
                val obj = JSONObject()
                obj.put("ip", dev.ip)
                obj.put("mac", dev.mac)
                obj.put("hostname", dev.hostname)
                obj.put("vendor", dev.vendor)
                obj.put("latencyMs", dev.responseTimeMs)
                obj.put("deviceType", dev.deviceType)
                obj.put("services", JSONArray(dev.services))
                obj.put("openPorts", JSONArray(dev.openPorts))
                arr.put(obj)
            }
            root.put("devices", arr)
            root.toString(2)
        } else {
            buildString {
                appendLine("# Enterweb Slinger - LAN Discovery Report")
                appendLine("Generated: $now")
                appendLine("Network SSID: **${topology.ssid}** (${topology.frequencyBand})")
                appendLine("Default Gateway: `${topology.defaultGateway}` | Subnet: `/${topology.subnetCidr}`")
                appendLine("Total Devices Discovered: **${devices.size}**")
                appendLine()
                appendLine("| IP Address | Hostname / Label | Vendor | Latency | Services / Open Ports |")
                appendLine("|---|---|---|---|---|")
                devices.forEach { dev ->
                    val services = (dev.services + dev.openPorts.map { "Port $it" }).joinToString(", ").ifBlank { "None" }
                    val label = dev.customLabel ?: dev.hostname
                    appendLine("| `${dev.ip}` | $label | ${dev.vendor} | ${dev.responseTimeMs} ms | $services |")
                }
                appendLine()
                appendLine("---")
                appendLine("*Generated by Enterweb Slinger Network Analyzer*")
            }
        }

        launchShareIntent(context, "Enterweb Slinger - LAN Report", content)
    }

    fun sharePingReport(
        context: Context,
        summary: PingSummary,
        formatAsJson: Boolean = false
    ) {
        val now = dateFormat.format(Date())
        val content = if (formatAsJson) {
            val root = JSONObject()
            root.put("title", "Enterweb Slinger - Ping Diagnostic Report")
            root.put("generatedAt", now)
            root.put("host", summary.host)
            root.put("ip", summary.ip)
            root.put("protocol", summary.protocol)
            root.put("packetsSent", summary.packetsSent)
            root.put("packetsReceived", summary.packetsReceived)
            root.put("packetLossPercent", summary.packetLossPercent)
            root.put("minRttMs", summary.minRttMs)
            root.put("avgRttMs", summary.avgRttMs)
            root.put("maxRttMs", summary.maxRttMs)
            root.put("jitterMs", summary.jitterMs)

            val arr = JSONArray()
            summary.results.forEach { r ->
                val obj = JSONObject()
                obj.put("seq", r.seq)
                obj.put("rttMs", r.rttMs)
                obj.put("ttl", r.ttl)
                obj.put("success", r.isSuccess)
                obj.put("error", r.errorMessage ?: "")
                arr.put(obj)
            }
            root.put("pings", arr)
            root.toString(2)
        } else {
            buildString {
                appendLine("# Enterweb Slinger - Ping Diagnostic Report")
                appendLine("Generated: $now")
                appendLine("Target: **${summary.host}** (`${summary.ip}`) via **${summary.protocol}**")
                appendLine()
                appendLine("### Telemetry Summary")
                appendLine("- Packets: Sent = ${summary.packetsSent}, Received = ${summary.packetsReceived}, Loss = ${String.format("%.1f%%", summary.packetLossPercent)}")
                appendLine("- Round-Trip Time: Min = ${String.format("%.2f ms", summary.minRttMs)}, Avg = ${String.format("%.2f ms", summary.avgRttMs)}, Max = ${String.format("%.2f ms", summary.maxRttMs)}")
                appendLine("- Jitter (Mean Absolute Deviation): ${String.format("%.2f ms", summary.jitterMs)}")
                appendLine()
                appendLine("### Detailed Packet Logs")
                appendLine("| Seq | Host | RTT | TTL | Status |")
                appendLine("|---|---|---|---|---|")
                summary.results.forEach { r ->
                    val status = if (r.isSuccess) "OK" else (r.errorMessage ?: "Timeout")
                    appendLine("| #${r.seq} | `${r.ip}` | ${String.format("%.1f ms", r.rttMs)} | ${r.ttl} | $status |")
                }
                appendLine()
                appendLine("---")
                appendLine("*Generated by Enterweb Slinger Network Analyzer*")
            }
        }

        launchShareIntent(context, "Enterweb Slinger - Ping Report (${summary.host})", content)
    }

    private fun launchShareIntent(context: Context, title: String, content: String) {
        val sendIntent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_SUBJECT, title)
            putExtra(Intent.EXTRA_TEXT, content)
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }

        try {
            val reportsDir = java.io.File(context.cacheDir, "reports").apply { mkdirs() }
            val sanitized = title.replace("[^a-zA-Z0-9.-]".toRegex(), "_")
            val reportFile = java.io.File(reportsDir, "${sanitized}_${System.currentTimeMillis()}.txt")
            reportFile.writeText(content, Charsets.UTF_8)

            val uri = androidx.core.content.FileProvider.getUriForFile(
                context,
                "${context.packageName}.fileprovider",
                reportFile
            )
            sendIntent.putExtra(Intent.EXTRA_STREAM, uri)
            sendIntent.addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        } catch (_: Exception) {}

        val chooser = Intent.createChooser(sendIntent, title).apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        context.startActivity(chooser)
    }
}
